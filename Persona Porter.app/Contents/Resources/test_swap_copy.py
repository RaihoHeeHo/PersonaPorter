from pathlib import Path
import struct
import tempfile
import unittest

from persona_porter import FormatError, Region, select
from swap_copy import BuildCancelled, build_swap, plan_swap, verify_unchanged_outside
from test_persona_porter import image


def model(data):
    return struct.pack('<III', 16, len(data), 0x1803ffff) + data


class SwapTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.target = self.root / 'target.iso'
        self.source = self.root / 'source.iso'
        self.output = self.root / 'new.iso'
        self.target.write_bytes(image(image(model(b'original longer'), prefix=0x1800), b'BTL.CVM;1'))
        self.source.write_bytes(image(image(model(b'new'), prefix=0x1800), b'DATA.CVM;1'))
        self.pairs = [('DATA.CVM!MODEL.RMD', 'BTL.CVM!MODEL.RMD')]

    def test_nested_swap_and_full_preservation(self):
        before = self.target.read_bytes()
        plan = build_swap(self.target, self.source, self.pairs, self.output)
        self.assertEqual(self.target.read_bytes(), before)
        self.assertEqual(self.output.stat().st_size, len(before))
        with self.output.open('rb') as f:
            r = select(Region(f), 'BTL.CVM!MODEL.RMD')
            self.assertEqual(r.read(0, r.size), model(b'new'))
        self.assertTrue(plan['verification']['all_bytes_outside_planned_ranges_unchanged'])

    def test_refuse_growing_file_before_copy(self):
        self.source.write_bytes(image(image(model(b'x' * 200)), b'DATA.CVM;1'))
        with self.assertRaisesRegex(FormatError, 'exceeds'):
            build_swap(self.target, self.source, self.pairs, self.output)
        self.assertFalse(self.output.exists())

    def test_existing_output_preserved(self):
        self.output.write_bytes(b'keep')
        with self.assertRaises(FileExistsError):
            build_swap(self.target, self.source, self.pairs, self.output)
        self.assertEqual(self.output.read_bytes(), b'keep')

    def test_original_as_output_refused(self):
        before = self.target.read_bytes()
        with self.assertRaises(FileExistsError):
            build_swap(self.target, self.source, self.pairs, self.target)
        self.assertEqual(self.target.read_bytes(), before)

    def test_duplicate_target_refused(self):
        with self.assertRaisesRegex(FormatError, 'Overlapping'):
            plan_swap(self.target, self.source, self.pairs * 2)

    def test_unexpected_outside_mutation_detected(self):
        plan = build_swap(self.target, self.source, self.pairs, self.output)
        with self.output.open('r+b') as f:
            f.seek(0)
            f.write(b'X')
        with self.assertRaisesRegex(FormatError, 'Unexpected change'):
            verify_unchanged_outside(self.target, self.output, plan['allowed_change_ranges'])

    def test_generated_equal_size_file(self):
        payload = model(b'generated bytes')
        result = build_swap(self.target, self.source, [], self.output,
                            {'BTL.CVM!MODEL.RMD': payload})
        self.assertTrue(result['verification']['replacement_bytes_match_source'])
        with self.output.open('rb') as f:
            r = select(Region(f), 'BTL.CVM!MODEL.RMD')
            self.assertEqual(r.read(0, r.size), payload)

    def test_generated_size_mismatch_rejected(self):
        with self.assertRaisesRegex(FormatError, 'exact original file size'):
            build_swap(self.target, self.source, [], self.output,
                       {'BTL.CVM!MODEL.RMD': b'short'})
        self.assertFalse(self.output.exists())

    def test_cancellation_cleans_partial_output(self):
        cancelled = False
        def progress(stage, percent):
            nonlocal cancelled
            if stage == 'Copying the target ISO':
                cancelled = True
        with self.assertRaises(BuildCancelled):
            build_swap(self.target, self.source, self.pairs, self.output,
                       progress=progress, cancel=lambda: cancelled)
        self.assertFalse(self.output.exists())

    def test_build_progress_reaches_verified_completion(self):
        seen = []
        build_swap(self.target, self.source, self.pairs, self.output,
                   progress=lambda stage, value: seen.append((stage, value)))
        self.assertEqual(seen[-1], ('Verified', 100))
        self.assertTrue(all(0 <= value <= 100 for _, value in seen))


if __name__ == '__main__':
    unittest.main()
